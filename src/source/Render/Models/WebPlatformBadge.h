#pragma once

// Transparent globe-and-pointer silhouette shared by OpenGL and Vulkan.
namespace ParisPlatform::WebMark {
constexpr int Side = 32;
constexpr const char* Rows[Side] = {
    "00000000001111111100000000000000",
    "00000000111111111111000000000000",
    "00000011111111111111110000000000",
    "00000111011001100110111000000000",
    "00001110011001100110011100000000",
    "00011100110001100011001110000000",
    "00111111111111111111111111000000",
    "00111111111111111111111111000000",
    "01100000100001100001000001100000",
    "01100001100001100001100001100000",
    "11100001100001100001100001110000",
    "11000001000001000000100000110000",
    "11000001000000011110000000110000",
    "11111111111110111111110001110000",
    "11111111111101110011111110000000",
    "11000001000001100000011111111000",
    "11000001000001100000000001111111",
    "11100001100001100000000000001111",
    "01100001100001110000000000011110",
    "01100000100000110000000001111000",
    "00111111111110110000000011100000",
    "00111111111110110000000011100000",
    "00011100110001011000000001110000",
    "00001110011001011000110000111000",
    "00000111011001011000111000011100",
    "00000011111111011001111100001110",
    "00000000111111101101101110001110",
    "00000000001111101111100111011100",
    "00000000000000001111000011111000",
    "00000000000000001111000001110000",
    "00000000000000000110000000000000",
    "00000000000000000110000000000000",
};

template<class DrawRectangle>
void Draw(float x, float y, float size, DrawRectangle draw) {
    constexpr float Inset = 1.5f;
    const float pixel = (size - Inset * 2.0f) / Side;
    for (int row = 0; row < Side; ++row) {
        int column = 0;
        while (column < Side) {
            if (Rows[row][column] != '1') { ++column; continue; }
            const int start = column;
            while (column < Side && Rows[row][column] == '1') ++column;
            draw(x + Inset + start * pixel, y + Inset + row * pixel,
                 (column - start) * pixel, pixel);
        }
    }
}
} // namespace ParisPlatform::WebMark
